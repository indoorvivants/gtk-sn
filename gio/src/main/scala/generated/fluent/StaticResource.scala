package sn.gnome.gio

import _root_.sn.gnome.gio.internal.*

import _root_.scala.scalanative.unsafe.*

import sn.gnome.gio.Resource
import sn.gnome.gio.internal.GStaticResource

/** #GStaticResource is an opaque data structure and can only be accessed using
  * the following functions.
  *
  * NOTE: THIS IS A COMMENT FOR THE ORIGINAL C DEFINITION, NOT ALL DETAILS MIGHT
  * BE APPLICABLE TO SCALA
  */
class StaticResource private[gnome] (raw: Ptr[GStaticResource]):

  def getUnsafeRawPointer(): Ptr[GStaticResource] = this.raw

  /** Finalized a GResource initialized by g_static_resource_init().
    *
    * This is normally used by code generated by
    * [glib-compile-resources][glib-compile-resources] and is not typically used
    * by other code.
    *
    * NOTE: THIS IS A COMMENT FOR THE ORIGINAL C DEFINITION, NOT ALL DETAILS
    * MIGHT BE APPLICABLE TO SCALA
    */
  def fini(): Unit /* None */ =
    g_static_resource_fini(
      this.getUnsafeRawPointer().asInstanceOf[Ptr[GStaticResource]]
    )
  end fini

  /** Gets the GResource that was registered by a call to
    * g_static_resource_init().
    *
    * This is normally used by code generated by
    * [glib-compile-resources][glib-compile-resources] and is not typically used
    * by other code.
    *
    * NOTE: THIS IS A COMMENT FOR THE ORIGINAL C DEFINITION, NOT ALL DETAILS
    * MIGHT BE APPLICABLE TO SCALA
    */
  def getResource(): sn.gnome.gio.Resource /* None */ =
    sn.gnome.gio.Resource.fromRaw(
      g_static_resource_get_resource(
        this.getUnsafeRawPointer().asInstanceOf[Ptr[GStaticResource]]
      )
    )
  end getResource

  /** Initializes a GResource from static data using a GStaticResource.
    *
    * This is normally used by code generated by
    * [glib-compile-resources][glib-compile-resources] and is not typically used
    * by other code.
    *
    * NOTE: THIS IS A COMMENT FOR THE ORIGINAL C DEFINITION, NOT ALL DETAILS
    * MIGHT BE APPLICABLE TO SCALA
    */
  def init(): Unit /* None */ =
    g_static_resource_init(
      this.getUnsafeRawPointer().asInstanceOf[Ptr[GStaticResource]]
    )
  end init

end StaticResource

object StaticResource:
  def fromRaw(ptr: Ptr[GStaticResource]): StaticResource = new StaticResource(
    ptr
  )
end StaticResource
