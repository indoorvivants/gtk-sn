package sn.gnome.glib.fluent

import _root_.sn.gnome.glib.internal.GMarkupParseFlags

/** COMMENT FOR THE ORIGINAL C DEFINITION
  *
  * Flags that affect the behaviour of the parser.
  */
class MarkupParseFlags private (val raw: GMarkupParseFlags):
  def is(kv: MarkupParseFlags): Boolean =
    raw.is(kv.raw)

  override def toString(): String =
    var rem = raw.value
    val sb = List.newBuilder[MarkupParseFlags.KnownValue]
    MarkupParseFlags.KnownValue.values.foreach: kv =>
      if this.is(kv) then sb += kv

      rem = rem & (~kv.raw.value)

    s"MarkupParseFlags(${sb.result().mkString(", ")})"
end MarkupParseFlags

object MarkupParseFlags:
  export KnownValue.*

  def fromRaw(raw: GMarkupParseFlags) = new MarkupParseFlags(raw)

  extension (af: MarkupParseFlags)
    def &(other: MarkupParseFlags) =
      MarkupParseFlags(af.raw & other.raw)
    def |(other: MarkupParseFlags) =
      MarkupParseFlags(af.raw | other.raw)

  /** COMMENT FOR THE ORIGINAL C DEFINITION
    *
    * Flags that affect the behaviour of the parser.
    */
  enum KnownValue(override val raw: GMarkupParseFlags, name: String)
      extends MarkupParseFlags(raw):
    override def toString(): String = this.name

    /** COMMENT FOR THE ORIGINAL C DEFINITION
      *
      * No special behaviour. Since: 2.74
      */
    case DEFAULT_FLAGS
        extends KnownValue(
          GMarkupParseFlags.G_MARKUP_DEFAULT_FLAGS,
          "DEFAULT_FLAGS"
        )

    /** COMMENT FOR THE ORIGINAL C DEFINITION
      *
      * flag you should not use
      */
    case DO_NOT_USE_THIS_UNSUPPORTED_FLAG
        extends KnownValue(
          GMarkupParseFlags.G_MARKUP_DO_NOT_USE_THIS_UNSUPPORTED_FLAG,
          "DO_NOT_USE_THIS_UNSUPPORTED_FLAG"
        )

    /** COMMENT FOR THE ORIGINAL C DEFINITION
      *
      * When this flag is set, CDATA marked sections are not passed literally to
      * the @passthrough function of the parser. Instead, the content of the
      * section (without the `<![CDATA[` and `]]>`) is passed to the @text
      * function. This flag was added in GLib 2.12
      */
    case TREAT_CDATA_AS_TEXT
        extends KnownValue(
          GMarkupParseFlags.G_MARKUP_TREAT_CDATA_AS_TEXT,
          "TREAT_CDATA_AS_TEXT"
        )

    /** COMMENT FOR THE ORIGINAL C DEFINITION
      *
      * Normally errors caught by GMarkup itself have line/column information
      * prefixed to them to let the caller know the location of the error. When
      * this flag is set the location information is also prefixed to errors
      * generated by the #GMarkupParser implementation functions
      */
    case PREFIX_ERROR_POSITION
        extends KnownValue(
          GMarkupParseFlags.G_MARKUP_PREFIX_ERROR_POSITION,
          "PREFIX_ERROR_POSITION"
        )

    /** COMMENT FOR THE ORIGINAL C DEFINITION
      *
      * Ignore (don't report) qualified attributes and tags, along with their
      * contents. A qualified attribute or tag is one that contains ':' in its
      * name (ie: is in another namespace). Since: 2.40.
      */
    case IGNORE_QUALIFIED
        extends KnownValue(
          GMarkupParseFlags.G_MARKUP_IGNORE_QUALIFIED,
          "IGNORE_QUALIFIED"
        )
  end KnownValue
end MarkupParseFlags
