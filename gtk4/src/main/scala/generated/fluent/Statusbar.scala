      context_id: UInt /* Some(_root_.sn.gnome.glib.internal.guint) */
  ): Unit /* None */ =
    gtk_statusbar_pop(
      this.getUnsafeRawPointer().asInstanceOf[Ptr[GtkStatusbar]],
      guint(context_id)
