/** COMMENT FOR THE ORIGINAL C DEFINITION
  *
  * A `GtkStatusbar` widget is usually placed along the bottom of an
  * application's main [class@Gtk.Window].
  *
  * ![An example GtkStatusbar](statusbar.png)
  *
  * A `GtkStatusBar` may provide a regular commentary of the application's
  * status (as is usually the case in a web browser, for example), or may be
  * used to simply output a message when the status changes, (when an upload is
  * complete in an FTP client, for example).
  *
  * Status bars in GTK maintain a stack of messages. The message at the top of
  * the each bar’s stack is the one that will currently be displayed.
  *
  * Any messages added to a statusbar’s stack must specify a context id that is
  * used to uniquely identify the source of a message. This context id can be
  * generated by [method@Gtk.Statusbar.get_context_id], given a message and the
  * statusbar that it will be added to. Note that messages are stored in a
  * stack, and when choosing which message to display, the stack structure is
  * adhered to, regardless of the context identifier of a message.
  *
  * One could say that a statusbar maintains one stack of messages for display
  * purposes, but allows multiple message producers to maintain sub-stacks of
  * the messages they produced (via context ids).
  *
  * Status bars are created using [ctor@Gtk.Statusbar.new].
  *
  * Messages are added to the bar’s stack with [method@Gtk.Statusbar.push].
  *
  * The message at the top of the stack can be removed using
  * [method@Gtk.Statusbar.pop]. A message can be removed from anywhere in the
  * stack if its message id was recorded at the time it was added. This is done
  * using [method@Gtk.Statusbar.remove].
  *
  * ## CSS node
  *
  * `GtkStatusbar` has a single CSS node with name `statusbar`.
  */
class Statusbar(raw: Ptr[GtkStatusbar])
    extends Widget(raw.asInstanceOf),
      Accessible,
      Buildable,
      ConstraintTarget:

  override def getUnsafeRawPointer(): Ptr[Byte] = this.raw.asInstanceOf

  /** COMMENT FOR THE ORIGINAL C DEFINITION
    *
    * Returns a new context identifier, given a description of the actual
    * context.
    *
    * Note that the description is not shown in the UI.
    */
  def getContextId(
      context_description: String | CString /* Some(CString) */
  )(using Zone): UInt /* None */ = gtk_statusbar_get_context_id(
    this.raw.asInstanceOf[Ptr[GtkStatusbar]],
    __sn_extract_string(context_description)
  ).value

  /** COMMENT FOR THE ORIGINAL C DEFINITION
    *
    * Removes the first message in the `GtkStatusbar`’s stack with the given
    * context id.
    *
    * Note that this may not change the displayed message, if the message at the
    * top of the stack has a different context id.
    */
  def pop(
      context_id: UInt /* Some(_root_.sn.gnome.glib.internal.guint) */
  ): Unit /* None */ = gtk_statusbar_pop(
    this.raw.asInstanceOf[Ptr[GtkStatusbar]],
    guint(context_id)
  )

  /** COMMENT FOR THE ORIGINAL C DEFINITION
    *
    * Pushes a new message onto a statusbar’s stack.
    */
  def push(
      context_id: UInt /* Some(_root_.sn.gnome.glib.internal.guint) */,
      text: String | CString /* Some(CString) */
  )(using Zone): UInt /* None */ = gtk_statusbar_push(
    this.raw.asInstanceOf[Ptr[GtkStatusbar]],
    guint(context_id),
    __sn_extract_string(text)
  ).value

  /** COMMENT FOR THE ORIGINAL C DEFINITION
    *
    * Forces the removal of a message from a statusbar’s stack. The exact @context_id
    * and @message_id must be specified.
    */
  def remove(
      context_id: UInt /* Some(_root_.sn.gnome.glib.internal.guint) */,
      message_id: UInt /* Some(_root_.sn.gnome.glib.internal.guint) */
  ): Unit /* None */ = gtk_statusbar_remove(
    this.raw.asInstanceOf[Ptr[GtkStatusbar]],
    guint(context_id),
    guint(message_id)
  )

  /** COMMENT FOR THE ORIGINAL C DEFINITION
    *
    * Forces the removal of all messages from a statusbar's stack with the exact @context_id.
    */
  def removeAll(
      context_id: UInt /* Some(_root_.sn.gnome.glib.internal.guint) */
  ): Unit /* None */ = gtk_statusbar_remove_all(
    this.raw.asInstanceOf[Ptr[GtkStatusbar]],
    guint(context_id)
  )

  private inline def __sn_extract_string(str: String | CString)(using
      Zone
  ): CString =
    str match
      case s: String  => toCString(s)
      case s: CString => s
    end match
  end __sn_extract_string
end Statusbar

object Statusbar:
  /** COMMENT FOR THE ORIGINAL C DEFINITION
    *
    * Creates a new `GtkStatusbar` ready for messages.
    */
  def apply(): Statusbar = new Statusbar(gtk_statusbar_new().asInstanceOf)
end Statusbar
