package sn.gnome.gsk4

import _root_.sn.gnome.gsk4.internal.*

import _root_.scala.scalanative.unsafe.*

import sn.gnome.gobject.runtime.*
import sn.gnome.gsk4.{Path, RenderNode, Stroke}
import sn.gnome.gsk4.internal.GskStrokeNode

/** A render node that will fill the area determined by stroking the the given
  * [struct@Gsk.Path] using the [struct@Gsk.Stroke] attributes.
  *
  * NOTE: THIS IS A COMMENT FOR THE ORIGINAL C DEFINITION, NOT ALL DETAILS MIGHT
  * BE APPLICABLE TO SCALA
  */
class StrokeNode private[gnome] (raw: Ptr[GskStrokeNode])
    extends RenderNode(raw.asInstanceOf):

  override def getUnsafeRawPointer(): Ptr[Byte] = this.raw.asInstanceOf

  /** Gets the child node that is getting drawn by the given @node.
    *
    * NOTE: THIS IS A COMMENT FOR THE ORIGINAL C DEFINITION, NOT ALL DETAILS
    * MIGHT BE APPLICABLE TO SCALA
    */
  def getChild()(using Runtime): sn.gnome.gsk4.RenderNode /* None */ =
    sn.gnome.gsk4.RenderNode.applyUnsafe(
      gsk_stroke_node_get_child(
        this.getUnsafeRawPointer().asInstanceOf[Ptr[GskRenderNode]]
      ).asInstanceOf
    )
  end getChild

  /** Retrieves the path that will be stroked with the contents of the @node.
    *
    * NOTE: THIS IS A COMMENT FOR THE ORIGINAL C DEFINITION, NOT ALL DETAILS
    * MIGHT BE APPLICABLE TO SCALA
    */
  def getPath(): sn.gnome.gsk4.Path /* None */ =
    sn.gnome.gsk4.Path.fromRaw(
      gsk_stroke_node_get_path(
        this.getUnsafeRawPointer().asInstanceOf[Ptr[GskRenderNode]]
      )
    )
  end getPath

  /** Retrieves the stroke attributes used in this @node.
    *
    * NOTE: THIS IS A COMMENT FOR THE ORIGINAL C DEFINITION, NOT ALL DETAILS
    * MIGHT BE APPLICABLE TO SCALA
    */
  def getStroke(): sn.gnome.gsk4.Stroke /* None */ =
    sn.gnome.gsk4.Stroke.fromRaw(
      gsk_stroke_node_get_stroke(
        this.getUnsafeRawPointer().asInstanceOf[Ptr[GskRenderNode]]
      )
    )
  end getStroke

end StrokeNode

object StrokeNode:
  /** Creates or retrieves the wrapper object associated with the given pointer
    */
  def applyUnsafe(ptr: Ptr[GskStrokeNode])(using Runtime) =
    summon[Runtime].getOrCreate[StrokeNode](
      ptr.asInstanceOf[Ptr[Byte]],
      p => new StrokeNode(ptr)
    )

  /** Creates a #GskRenderNode that will fill the outline generated by stroking
    * the given @path using the attributes defined in @stroke.
    *
    * The area is filled with @child.
    *
    * NOTE: THIS IS A COMMENT FOR THE ORIGINAL C DEFINITION, NOT ALL DETAILS
    * MIGHT BE APPLICABLE TO SCALA
    */
  def apply(
      child: sn.gnome.gsk4.RenderNode /* Some(Ptr[GskRenderNode]) */,
      path: sn.gnome.gsk4.Path /* Some(Ptr[GskPath]) */,
      stroke: sn.gnome.gsk4.Stroke /* Some(Ptr[GskStroke]) */
  )(using Runtime): StrokeNode =
    val raw: Ptr[Byte] = gsk_stroke_node_new(
      child.getUnsafeRawPointer().asInstanceOf,
      path.getUnsafeRawPointer().asInstanceOf,
      stroke.getUnsafeRawPointer().asInstanceOf
    ).asInstanceOf
    summon[Runtime]
      .getOrCreate[StrokeNode](raw, r => StrokeNode.applyUnsafe(r.asInstanceOf))
  end apply
end StrokeNode
